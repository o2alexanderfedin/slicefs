#!/usr/bin/env python3
"""Prints crates/prolly/src/rule_table.rs: the fixed-point exp(-x) table.

    python3 scripts/prolly-table/gen_table.py > crates/prolly/src/rule_table.rs
    python3 scripts/prolly-table/gen_table.py --check crates/prolly/src/rule_table.rs

EXP_INT[i]  = round(2^32 * e^-i)       for i = 0..=22
EXP_FRAC[j] = round(2^32 * e^-(j/1024)) for j = 0..=1024

The values are computed with the decimal module at 60 digits and rounded
half up, so the output is the same on every machine. With --check FILE the
script compares FILE byte for byte with its output: exit 0 when equal,
exit 1 (and the first differing line on stderr) when not.
"""
import sys
from decimal import Decimal, ROUND_HALF_UP, getcontext

getcontext().prec = 60
SCALE = Decimal(2) ** 32


def scaled(x: Decimal) -> int:
    v = (SCALE * (-x).exp()).to_integral_value(rounding=ROUND_HALF_UP)
    return int(v)


def array(name: str, vals: list) -> str:
    lines = []
    for i in range(0, len(vals), 8):
        chunk = vals[i : i + 8]
        lines.append("    " + ", ".join(str(v) for v in chunk) + ",")
    return (
        "#[rustfmt::skip]\n"
        f"pub(crate) const {name}: [u64; {len(vals)}] = [\n" + "\n".join(lines) + "\n];\n"
    )


def render() -> str:
    exp_int = [scaled(Decimal(i)) for i in range(23)]
    exp_frac = [scaled(Decimal(j) / Decimal(1024)) for j in range(1025)]
    head = (
        "//! The fixed-point table of the boundary rule: `e^-x` scaled by 2^32.\n"
        "//!\n"
        "//! Generated by `scripts/prolly-table/gen_table.py`; do not edit by hand.\n"
        "//! `python3 scripts/prolly-table/gen_table.py --check <this file>` must exit 0.\n"
        "//!\n"
        "//! `EXP_INT[i]` = round(2^32 * e^-i) for i in 0..=22 and `EXP_FRAC[j]` =\n"
        "//! round(2^32 * e^-(j/1024)) for j in 0..=1024.\n\n"
    )
    return head + array("EXP_INT", exp_int) + "\n" + array("EXP_FRAC", exp_frac)


def main(argv: list) -> int:
    out = render()
    if len(argv) == 3 and argv[1] == "--check":
        with open(argv[2], "r", encoding="utf-8", newline="") as f:
            have = f.read()
        if have == out:
            return 0
        a, b = have.split("\n"), out.split("\n")
        for n in range(max(len(a), len(b))):
            x = a[n] if n < len(a) else "<end of file>"
            y = b[n] if n < len(b) else "<end of output>"
            if x != y:
                print(f"line {n + 1}: file has {x!r}, generator makes {y!r}", file=sys.stderr)
                break
        return 1
    if len(argv) == 1:
        sys.stdout.write(out)
        return 0
    print("usage: gen_table.py [--check FILE]", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
